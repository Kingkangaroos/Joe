'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'..','goal-quests.js'),'utf8');
const KEY='rpg_goal_quests_v1';
let now=new Date(2026,8,13,20).getTime();
class Clock extends Date{constructor(...args){super(...(args.length?args:[now]));}static now(){return now;}}
const weekly={id:'w1',type:'weekly',period:'2026-09-07',title:'Finished weekly result',steps:[{text:'Done',done:true}],rewarded:true,completedAt:'2026-09-13T10:00:00Z'};
const monthly={id:'m1',type:'monthly',period:'2026-09',title:'In-progress month',steps:[{text:'Pending',done:false}],rewarded:false};
let raw=JSON.stringify({version:1,weekly:{period:weekly.period,quest:weekly},monthly:{period:monthly.period,quest:monthly},history:[]});
let writes=0,rewards=0;
const host={innerHTML:''};
const window={addEventListener(){},dispatchEvent(){},addXP(){rewards++;},removeXP(){rewards++;}};
vm.runInNewContext(source,{window,Date:Clock,document:{readyState:'loading',addEventListener(){},getElementById:id=>id==='goalQuestCards'?host:null},localStorage:{getItem:k=>k===KEY?raw:null,setItem(k,v){assert.equal(k,KEY);raw=v;writes++;}},CustomEvent:function(){},setTimeout});
window.GamenfyGoalQuests.render();
assert.equal(writes,0,'same-period render leaves persisted state unchanged');
now=new Date(2026,8,14,8).getTime();
window.GamenfyGoalQuests.render();
let state=JSON.parse(raw);
assert.deepEqual(state.history,[weekly],'Monday archives the complete quest, including reward and completion metadata');
assert.deepEqual(state.weekly,{period:'2026-09-14',quest:null});
assert.deepEqual(state.monthly.quest,monthly,'Monday preserves the current monthly quest');
window.GamenfyGoalQuests.render();
assert.equal(JSON.parse(raw).history.length,1,'repeat render does not archive twice');
now=new Date(2026,9,1,8).getTime();
window.GamenfyGoalQuests.render();
state=JSON.parse(raw);
assert.deepEqual(state.history,[monthly,weekly],'new month preserves unfinished quests too and skips empty weeks');
assert.deepEqual(state.monthly,{period:'2026-10',quest:null});
assert.equal(rewards,0,'archiving never grants or removes XP');
state.history=Array.from({length:24},(_,i)=>({id:'old-'+i,title:'Old quest'}));
state.weekly={period:'2026-09-21',quest:weekly};raw=JSON.stringify(state);
window.GamenfyGoalQuests.render();
state=JSON.parse(raw);
assert.equal(state.history.length,24,'history retains its existing 24-quest cap');
assert.deepEqual(state.history[0],weekly,'newest archived quest is retained');
assert.equal(state.history[23].id,'old-22','only oldest history entry is pruned');
console.log('Command Quest rollover: completed and unfinished history, period boundaries, exact-once archival and unchanged XP passed.');
