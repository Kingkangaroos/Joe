'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const board=fs.readFileSync('website-ventures-higgsfield-prompt-board.html','utf8');
const review=fs.readFileSync('website-ventures-higgsfield-review.html','utf8');
const queue=JSON.parse(fs.readFileSync('WEBSITE-VENTURES-HIGGSFIELD-QUEUE.json','utf8'));
const manifest=JSON.parse(fs.readFileSync('WEBSITE-VENTURES-ASSET-IMPORT-MANIFEST.json','utf8'));
const line=fs.readFileSync('website-ventures-production-line-v3.html','utf8');
const workspace=fs.readFileSync('ventures-workspace.html','utf8');
const ventures=fs.readFileSync('ventures.js','utf8');
assert.equal(queue.status.batch4,'done','Batch 4 is marked done');
assert.equal(queue.status.nextBatch,5,'Batch 5 is next');
assert.deepEqual(queue.batches.map(b=>b.number),[5,6,7,8,9],'only remaining batches 5-9 are active');
const jobs=queue.batches.flatMap(b=>b.jobs||[]);
for(const concept of ['Transformation Sculpture','Website as Luxury Product','Material Performance']) assert.ok(jobs.some(j=>j.title===concept),concept+' hero concept exists');
assert.ok(jobs.some(j=>j.id==='PL-CHAR-001'),'technician master candidate job exists');
assert.ok(jobs.filter(j=>j.id.startsWith('PL-STORY-')).length>=3,'same-technician working scenes exist');
assert.ok(jobs.filter(j=>j.id.startsWith('AG-SUPPORT-')).length===3,'agency support visuals exist');
assert.ok(jobs.some(j=>j.modelId==='cinematic_studio_2_5'&&j.quality==='4K'),'4K final master path exists');
assert.ok(jobs.every(j=>j.prompt&&j.model&&j.aspectRatio&&j.quality&&j.count&&j.gate),'every remaining job is copy-ready and gated');
const manifestIds=new Set((manifest.assets||[]).map(a=>a.jobId));
assert.ok(jobs.every(j=>manifestIds.has(j.id)),'every queue job has a repo import target');
assert.ok((manifest.assets||[]).every(a=>a.targetPath&&a.targetPath.startsWith('website-ventures-assets/')),'all asset targets use the dedicated intake root');
const byId=new Map((manifest.assets||[]).map(a=>[a.jobId,a]));
for(const id of ['AG-HERO-TRANSFORM-001','AG-HERO-PRODUCT-001','AG-HERO-MATERIAL-001']){
  const asset=byId.get(id);
  assert.equal(asset.candidatePaths.length,3,id+' must have three collision-free intake paths');
}
assert.equal(byId.get('AG-HERO-MOBILE-001').candidatePaths.length,2,'mobile derivative must have two collision-free intake paths');
assert.equal(new Set((manifest.assets||[]).flatMap(a=>a.candidatePaths||[])).size,(manifest.assets||[]).flatMap(a=>a.candidatePaths||[]).length,'candidate intake paths must be globally unique');
assert.ok(board.includes('Batch 4 done. Next = Batch 5.'),'board surfaces current progress');
assert.ok(board.includes('WEBSITE-VENTURES-HIGGSFIELD-QUEUE.json'),'board reads durable queue JSON');
assert.ok(board.includes('WEBSITE-VENTURES-ASSET-IMPORT-MANIFEST.json'),'board reads the import manifest');
assert.ok(board.includes('Copy full setup'),'one-tap full setup copy exists');
assert.ok(board.includes('Copy prompt only'),'prompt-only copy exists');
assert.ok(board.includes('Copy filename'),'filename copy exists');
assert.ok(board.includes('navigator.clipboard.writeText'),'clipboard implementation exists');
assert.ok(board.includes('Generation complete'),'manual generation completion tracking is explicitly scoped');
assert.ok(board.includes("DONE_KEY='wv_higgsfield_queue_done_v1'"),'queue progress persists locally');
assert.ok(board.includes("REVIEW_KEY='wv_higgsfield_review_v2'"),'queue reads the variant-level review gate');
assert.ok(board.includes("j.id==='AG-HERO-MOBILE-001'&&!winnerFor(DESKTOP_IDS,review)"),'mobile generation remains locked until a desktop winner exists');
assert.ok(board.includes('RESOLVED REFERENCE FILE:'),'dependent prompts receive the exact selected reference path');
assert.ok(review.includes("const KEY='wv_higgsfield_review_v2'"),'review uses the variant-level state contract');
assert.ok(review.includes("const LEGACY_KEY='wv_higgsfield_review_v1'"),'existing review notes migrate forward');
assert.ok(review.includes("DESKTOP_IDS.includes(id)?'agency-desktop-winner'"),'only one desktop hero variant can be selected across all three concepts');
assert.ok(review.includes('Copy Batch 5 handoff'),'review can produce a compact handoff after generation');
assert.ok(review.includes('MOBILE REFERENCE FILE:'),'handoff identifies the exact mobile source reference');
assert.ok(board.includes('Resterende queue'),'progress summary is visible');
