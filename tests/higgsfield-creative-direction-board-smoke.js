assert.ok(line.includes('Batch 4 complete · Batch 5 next'),'Production Line v3 surfaces current batch state');
assert.ok(workspace.includes('href="website-ventures-higgsfield-prompt-board.html"'),'Ventures overview links the live generation queue');
assert.ok(workspace.includes('ventures.js?v=11.5'),'Ventures workspace busts cache for the refreshed task queue');
assert.ok(ventures.includes('const GAMENFY_FOCUS_VERSION = 5'),'Gamenfy Builder task queue is on the current focus version');
